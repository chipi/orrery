// Sanity check — every locale x key combo must be present.
for (const loc of LOCALES) {
  const m = T[loc];
  if (!m) throw new Error(`Missing translations for locale: ${loc}`);
  for (const k of KEYS) {
    if (typeof m[k] !== 'string' || m[k].length === 0) {
      throw new Error(`Missing translation: ${loc}.${k}`);
    }
  }
}

// Step 1: Merge into paraglide-key-overrides.json (source of truth for
// future propagator runs). Preserves existing keys; updates only the
// ones we own.
const overrides = JSON.parse(fs.readFileSync(OVERRIDES_PATH, 'utf8'));
for (const loc of LOCALES) {
  overrides[loc] = overrides[loc] ?? {};
  for (const k of KEYS) {
    overrides[loc][k] = T[loc][k];
  }
}
fs.writeFileSync(OVERRIDES_PATH, JSON.stringify(overrides, null, 2) + '\n', 'utf8');
console.error(
  `✓ scripts/paraglide-key-overrides.json updated (${LOCALES.length} × ${KEYS.length} entries)`,
);

// Step 2: Overwrite the en-US fallback values in each messages/<locale>.json
// with the native translation. The locale file is the runtime read.
for (const loc of LOCALES) {
  const p = path.join(MESSAGES_DIR, `${loc}.json`);
  const data = JSON.parse(fs.readFileSync(p, 'utf8'));
  let changed = 0;
  for (const k of KEYS) {
    if (data[k] !== T[loc][k]) {
      data[k] = T[loc][k];
      changed++;
    }
  }
  fs.writeFileSync(p, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.error(`✓ messages/${loc}.json updated (${changed} of ${KEYS.length} keys)`);
}

console.error('\nDone. Verify with: npm run i18n:compile && npm run typecheck');
