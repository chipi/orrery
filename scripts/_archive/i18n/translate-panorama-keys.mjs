/**
 * One-shot translator for the 41 panorama_* HUD i18n keys
 * (PRD-022 / ADR-074 / #286 Phase 3D-full follow-up).
 *
 * The Phase 3D-full commit landed the keys in en-US and propagated
 * en-US fallbacks to 13 non-en-US locale message files. This script
 * fills the gap with native translations:
 *
 *   1. Merge native translations into scripts/paraglide-key-overrides.json
 *   2. Overwrite the en-US-fallback values in each messages/<locale>.json
 *      with the native translation (so the locale file is the source-of-
 *      truth runtime read; the overrides file is the source-of-truth
 *      for regenerating after future propagator runs).
 *
 * Conservative on locale-specific conventions:
 *   - Cardinal directions use the locale's geographic conventions.
 *   - {variable} placeholders preserved verbatim — the paraglide
 *     runtime substitutes them by name.
 *   - The "SOL" prefix (Mars-mission convention) stays as "SOL" /
 *     "Sol" in all locales; like "NASA" or "PIA", it's a proper noun.
 *   - Short aria-labels and chip text stay short — translations don't
 *     have to be word-for-word, they have to be idiomatic + short.
 */
