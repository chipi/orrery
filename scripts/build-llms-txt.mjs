#!/usr/bin/env node
/**
 * llms.txt (llmstxt.org) and the generated guides index, for agents (GitHub #666).
 *
 *   node scripts/build-llms-txt.mjs           write llms.txt + docs/guides/index.md
 *   node scripts/build-llms-txt.mjs --check   exit 1 when either is stale, a link or an
 *                                              AGENTS.md anchor does not resolve, or
 *                                              llms.txt passes 30 KB (in validate-data)
 *
 * The hand-kept part (summary, notes, area and service maps) is scripts/llms/llms-hand.mjs;
 * every link's note comes from the target's own title, so notes cannot drift from the docs.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as hand from './llms/llms-hand.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const LLMS = 'llms.txt';
const GUIDES_INDEX = 'docs/guides/index.md';
const MAX_BYTES = 30_000;

// Files this script writes are read from memory, so a first run (or a stale one) titles them right.
const generated = new Map();
const read = (rel) => generated.get(rel) ?? readFileSync(join(ROOT, rel), 'utf8');

/** GitHub's heading anchor: lowercase, punctuation dropped, each space a hyphen. */
export function slug(heading) {
  return heading
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');
}

const ID_DIRS = { ADR: 'docs/adr', RFC: 'docs/rfc', PRD: 'docs/prd', UXD: 'docs/uxs/decisions' };

/** `ADR-058` → `docs/adr/ADR-058.md` (or its `ADR-058-<slug>.md`); a path stays a path. */
export function resolveRef(ref) {
  const m = /^(ADR|RFC|PRD|UXD)-(\d{3})$/.exec(ref);
  if (!m) return ref;
  const dir = ID_DIRS[m[1]];
  const hit = readdirSync(join(ROOT, dir))
    .filter((f) => f === `${ref}.md` || f.startsWith(`${ref}-`))
    .sort()[0];
  if (!hit) throw new Error(`llms: ${ref} has no file in ${dir}`);
  return `${dir}/${hit}`;
}

/** A doc's title: its H1, or a skill's `name:`; markdown stripped. */
export function titleOf(md, fallback) {
  const fm = /^---\n([\s\S]*?)\n---/.exec(md);
  const h1 = /^#\s+(.+)$/m.exec(md.replace(/^---\n[\s\S]*?\n---/, ''));
  const t = h1?.[1] ?? /^name:\s*(.+)$/m.exec(fm?.[1] ?? '')?.[1] ?? fallback;
  return plain(t);
}

function plain(s) {
  return s
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[*_]{1,2}([^*_]+)[*_]{1,2}/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}

/** The first prose sentence of a section: skips headings, tables, code, lists of links. */
export function firstSentence(md, max = 150) {
  let inCode = false;
  for (const raw of md.split('\n')) {
    const line = raw.trim();
    if (line.startsWith('```')) {
      inCode = !inCode;
      continue;
    }
    if (inCode || !line || /^(#|\||<|---|```|- \[|\* \[|!\[)/.test(line)) continue;
    const text = plain(
      line
        .replace(/^>\s*/, '')
        .replace(/^[-*]\s+/, '')
        .replace(/`/g, ''),
    );
    if (text.length < 20) continue;
    // A sentence ends at . ! ? before a capital or the end, so "e.g. /fly" does not cut it.
    const sentence = /^(.+?[.!?])(?=\s+[A-Z"'(]|$)/.exec(text)?.[1] ?? text;
    return sentence.length > max ? `${sentence.slice(0, max - 1).trimEnd()}…` : sentence;
  }
  return '';
}

function linkLine(ref, note) {
  const path = resolveRef(ref);
  const [file] = path.split('#');
  const title = note ?? titleOf(read(file), file);
  return `- [${path.includes('#') ? path.split('#')[1].replace(/-+/g, ' ') : file}](${path}): ${title}`;
}

/** AGENTS.md, one line per H2 section, linked by its anchor. */
function agentRules() {
  const md = read('AGENTS.md');
  const parts = md.split(/^## /m).slice(1);
  return parts.map((part) => {
    const [head, ...rest] = part.split('\n');
    const note = hand.AGENT_RULE_NOTES[plain(head)] ?? firstSentence(rest.join('\n'), 140);
    return `- [${plain(head)}](AGENTS.md#${slug(head)})${note ? `: ${note}` : ''}`;
  });
}

/** docs/guides/index.md: every guide with its title and first sentence. */
export function buildGuidesIndex() {
  const files = readdirSync(join(ROOT, 'docs/guides'))
    .filter((f) => f.endsWith('.md') && f !== 'index.md' && f !== 'README.md')
    .sort();
  const rows = files.map((f) => {
    const md = read(`docs/guides/${f}`);
    const body = md.replace(/^---\n[\s\S]*?\n---/, '').replace(/^#\s+.+$/m, '');
    // Escaped: the docs site compiles this page with Vue, and a stripped code span like `<id>`
    // would read as an unclosed element.
    const note = firstSentence(body, 160).replace(/</g, '&lt;').replace(/>/g, '&gt;');
    return `- [${titleOf(md, f)}](${f})${note ? `: ${note}` : ''}`;
  });
  return [
    '# Guides',
    '',
    '<!-- Generated by scripts/build-llms-txt.mjs (npm run llms:build); do not edit by hand. -->',
    '',
    'Runbooks, style guides and contributor guides, one line each: the title and the first sentence of the guide.',
    '',
    ...rows,
    '',
  ].join('\n');
}

export function buildLlmsTxt() {
  const out = [
    '# Orrery',
    '',
    `> ${hand.SUMMARY}`,
    '',
    ...hand.NOTES.flatMap((n) => [n, '']),
    '## Agent rules',
    '',
  ];
  out.push(...agentRules(), '');
  out.push('## Decisions and specs', '');
  out.push(...hand.INDEXES.map((r) => linkLine(r)));
  out.push(...hand.MUST_KNOW.map((r) => linkLine(r)), '');
  out.push('## By area', '');
  for (const a of hand.AREAS) {
    out.push(`### ${a.area}`, '', `Code: ${a.code}`, '', ...a.docs.map((r) => linkLine(r)), '');
  }
  out.push('## By service', '');
  for (const s of hand.SERVICES) {
    out.push(`### ${s.name}`, '', `${s.what}.`, '', ...s.docs.map((r) => linkLine(r)), '');
  }
  out.push('## Optional', '', ...hand.OPTIONAL.map((r) => linkLine(r)), '');
  return out.join('\n');
}

/** Every link target exists; every AGENTS.md anchor is a heading there. */
export function linkProblems(text, baseDir = '') {
  const anchors = new Set(
    read('AGENTS.md')
      .split('\n')
      .filter((l) => /^#{1,6}\s/.test(l))
      .map((l) => slug(l.replace(/^#+\s+/, ''))),
  );
  const problems = [];
  for (const [, target] of text.matchAll(/\]\(([^)\s]+)\)/g)) {
    if (/^[a-z]+:/.test(target)) continue;
    const [file, anchor] = target.split('#');
    const rel = baseDir ? join(baseDir, file) : file;
    if (file && !generated.has(rel) && !existsSync(join(ROOT, rel)))
      problems.push(`missing file: ${target}`);
    else if (anchor && rel === 'AGENTS.md' && !anchors.has(anchor))
      problems.push(`missing anchor: ${target}`);
  }
  return problems;
}

function main() {
  const check = process.argv.includes('--check');
  const guides = buildGuidesIndex();
  generated.set(GUIDES_INDEX, guides);
  const llms = buildLlmsTxt();
  const problems = [...linkProblems(llms), ...linkProblems(guides, 'docs/guides')];
  const bytes = Buffer.byteLength(llms);
  if (bytes > MAX_BYTES) problems.push(`llms.txt is ${bytes} bytes, over ${MAX_BYTES}`);
  if (check) {
    for (const [rel, want] of [
      [LLMS, llms],
      [GUIDES_INDEX, guides],
    ]) {
      const have = existsSync(join(ROOT, rel)) ? read(rel) : '';
      if (have !== want) problems.push(`${rel} is stale: run npm run llms:build`);
    }
  } else {
    writeFileSync(join(ROOT, LLMS), llms);
    writeFileSync(join(ROOT, GUIDES_INDEX), guides);
  }
  for (const p of problems) console.error(`llms: ${p}`);
  console.log(
    `llms: ${check ? 'check' : 'wrote'} llms.txt (${bytes} bytes, ${llms.split('\n').filter((l) => l.startsWith('- [')).length} links) + ${GUIDES_INDEX} — ${problems.length ? 'FAIL' : 'PASS'}`,
  );
  if (problems.length) process.exit(1);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
