/**
 * Writes src/lib/three/showcase-index.ts: fleet id → the showcase family file that models it, so a
 * page can tell whether a craft has a 3D model (and load only that family) without importing the
 * models. Run after adding or renaming a showcase model; showcase-index.test.ts fails until it is.
 *
 *   npx tsx scripts/build-showcase-index.ts
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import type { ShowcaseModel } from '../src/lib/three/showcase/types';

const DIR = 'src/lib/three/showcase';
const OUT = 'src/lib/three/showcase-index.ts';

const index: Record<string, string> = {};
for (const file of readdirSync(DIR).sort()) {
  if (!file.endsWith('.ts') || file.endsWith('.test.ts') || file.includes('.tmp.')) continue;
  const family = file.replace(/\.ts$/, '');
  const mod = (await import(`../${DIR}/${file}`)) as {
    SHOWCASE?: Record<string, ShowcaseModel>;
  };
  for (const id of Object.keys(mod.SHOWCASE ?? {})) index[id] = family;
}

const rows = Object.keys(index)
  .sort()
  .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(index[id])},`)
  .join('\n');
writeFileSync(
  OUT,
  `// Generated by scripts/build-showcase-index.ts — do not edit by hand.
/** Fleet id → the showcase family file (src/lib/three/showcase/<family>.ts) that models it. */
export const SHOWCASE_FAMILY: Readonly<Record<string, string>> = {
${rows}
};

/** Whether the fleet entry has a true-size 3D model. */
export function hasShowcaseModel(fleetId: string | null | undefined): boolean {
  return !!fleetId && fleetId in SHOWCASE_FAMILY;
}
`,
);
execFileSync('npx', ['prettier', '--write', OUT], { stdio: 'ignore' });
console.log(`${OUT}: ${Object.keys(index).length} models`);
