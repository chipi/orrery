/**
 * The Roadster's /fly path from JPL Horizons (target -143205, "Tesla Roadster (AKA: Starman,
 * 2018-017A)"): heliocentric ecliptic J2000 position vectors, every 10 days from the first day
 * Horizons covers to the closest Mars passage (7 Oct 2020), written as
 * static/data/fly-trajectories/falcon-heavy-demo.json. Unlike generate-fly-trajectory.ts (a conic
 * between encounters) these are the measured orbit; the Mars passage at 0.0495 au is not snapped to
 * Mars, so it carries no label.
 *
 * Read-only network use: the public Horizons API, no key. Run: npx tsx scripts/fly/roadster-horizons-path.ts
 * It also prints Earth's Horizons vector beside the app's earthPos on the launch day, as the check
 * that the axes map x = X, z = Y (ecliptic).
 */
import { writeFileSync } from 'node:fs';
import { earthPos } from '../../src/lib/physics/transfer/mission-arc';
import { dateToSimDay } from '../../src/lib/sim-day';

const API = 'https://ssd.jpl.nasa.gov/api/horizons.api';

async function vectors(target: string, start: string, stop: string, step: string) {
  const q = new URLSearchParams({
    format: 'text',
    COMMAND: `'${target}'`,
    EPHEM_TYPE: 'VECTORS',
    CENTER: "'500@10'",
    REF_PLANE: 'ECLIPTIC',
    REF_SYSTEM: 'ICRF',
    OUT_UNITS: 'AU-D',
    VEC_TABLE: '1',
    CSV_FORMAT: 'YES',
    START_TIME: `'${start}'`,
    STOP_TIME: `'${stop}'`,
    STEP_SIZE: `'${step}'`,
  });
  const res = await fetch(`${API}?${q}`);
  const text = await res.text();
  const body = text.split('$$SOE')[1]?.split('$$EOE')[0];
  if (!body) throw new Error(`Horizons gave no table for ${target}:\n${text.slice(0, 1500)}`);
  return body
    .trim()
    .split('\n')
    .map((line) => {
      const c = line.split(',').map((s) => s.trim());
      // JDTDB, Calendar Date (TDB), X, Y, Z
      const date = c[1].replace(/^A\.D\. /, '').slice(0, 11);
      return { date, x: +c[2], y: +c[3], z: +c[4] };
    });
}

const MONTHS: Record<string, string> = {
  Jan: '01',
  Feb: '02',
  Mar: '03',
  Apr: '04',
  May: '05',
  Jun: '06',
  Jul: '07',
  Aug: '08',
  Sep: '09',
  Oct: '10',
  Nov: '11',
  Dec: '12',
};
const isoOf = (d: string) => {
  const [y, mon, day] = d.split('-');
  return `${y}-${MONTHS[mon]}-${day}`;
};

const earth = await vectors('399', '2018-02-07', '2018-02-08', '1d');
const app = earthPos(dateToSimDay('2018-02-07') as number);
console.log(
  'Earth 2018-02-07 Horizons X,Y:',
  earth[0].x.toFixed(4),
  earth[0].y.toFixed(4),
  ' app x,z:',
  app.x.toFixed(4),
  app.z.toFixed(4),
);

const car = [
  ...(await vectors('-143205', '2018-02-07 12:00', '2020-10-06', '10d')),
  ...(await vectors('-143205', '2020-10-07', '2020-10-08', '1d')).slice(0, 1),
];
const waypoints = [
  {
    date: '2018-02-06',
    label: 'Launch',
    x: +earth[0].x.toFixed(4),
    y: 0,
    z: +earth[0].y.toFixed(4),
  },
  ...car.map((p) => ({
    date: isoOf(p.date),
    x: +p.x.toFixed(4),
    y: +p.z.toFixed(4),
    z: +p.y.toFixed(4),
  })),
];
const last = car[car.length - 1];
console.log(
  'points',
  waypoints.length,
  'last',
  last.date,
  'r',
  Math.hypot(last.x, last.y).toFixed(3),
);
writeFileSync(
  'static/data/fly-trajectories/falcon-heavy-demo.json',
  JSON.stringify(
    {
      id: 'falcon-heavy-demo',
      source: 'jpl-horizons',
      _doc: 'Generated by scripts/fly/roadster-horizons-path.ts from JPL Horizons (target -143205): heliocentric ecliptic J2000 vectors every 10 days, x = X, z = Y, y = Z (AU). The measured orbit, not a conic between encounters; the Mars passage (0.0495 au, 7 Oct 2020) is not snapped to Mars.',
      waypoints,
    },
    null,
    1,
  ) + '\n',
);
