"""GlitchTip baseline for orrery: every issue seen in the last N days per project, as Markdown.

Run on the homelab mini (the read token lives there), through the host-run skill:

    ~/.claude/skills/host-run/scripts/run.sh homelab scripts/glitchtip-baseline.py [days=30] \
      > docs/ops/glitchtip-baseline-<date>.md

Compare a release against the newest baseline: an issue first seen after the deploy, or a known
one whose events jump, is the release's (deploy-verify gates only the first kind). Read-only.
Token and API: agentic-ai-homelab docs/recipes/agent-access.md §GlitchTip.
"""
import json
import os
import sys
import urllib.request
from datetime import datetime, timedelta, timezone

PROJECTS = ["orrery-prod", "orrery", "orrery-lab-api", "orrery-mcp"]
GT = "http://127.0.0.1:8090"
days = int(sys.argv[1]) if len(sys.argv) > 1 else 30


def token():
    for line in open(os.path.expanduser("~/signal-fleet/fleet-gateway.env")):
        if line.startswith("GLITCHTIP_TOKEN="):
            return line.split("=", 1)[1].strip().strip('"')
    raise SystemExit("GLITCHTIP_TOKEN not found")


TOKEN = token()


def get(path):
    req = urllib.request.Request(GT + path, headers={"Authorization": f"Bearer {TOKEN}"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r), r.headers.get("Link", "")


def issues(project):
    out, path = [], f"/api/0/projects/homelab/{project}/issues/?query=&limit=100"
    while path:
        page, link = get(path)
        out += page
        nxt = [p for p in link.split(",") if 'rel="next"' in p and 'results="true"' in p]
        path = nxt[0].split(";")[0].strip(" <>").replace(GT, "") if nxt else None
    return out


now = datetime.now(timezone.utc)
since = now - timedelta(days=days)
parse = lambda s: datetime.fromisoformat(s.replace("Z", "+00:00")) if s else None
print(f"# GlitchTip baseline — orrery, last {days} days ({since:%Y-%m-%d} → {now:%Y-%m-%d %H:%M} UTC)\n")
print("Generated by `scripts/glitchtip-baseline.py` (read-only). Events are the issue's total count;"
      " an issue is listed when it was last seen in the window.\n")
total = 0
for project in PROJECTS:
    rows = [i for i in issues(project) if (parse(i.get("lastSeen")) or now) >= since]
    rows.sort(key=lambda i: -int(i.get("count") or 0))
    total += len(rows)
    print(f"## {project} — {len(rows)} issues, {sum(int(i.get('count') or 0) for i in rows)} events\n")
    if not rows:
        print("None.\n")
        continue
    print("| Issue | Status | Events | First seen | Last seen | Title |")
    print("| --- | --- | ---: | --- | --- | --- |")
    for i in rows:
        title = (i.get("title") or "").replace("|", "\\|")[:90]
        print(f"| {i.get('shortId')} | {i.get('status')} | {i.get('count')} | {(i.get('firstSeen') or '')[:10]}"
              f" | {(i.get('lastSeen') or '')[:10]} | {title} |")
    print()
print(f"Total: {total} issues seen in the window.")
