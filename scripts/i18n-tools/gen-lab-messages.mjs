// Writes src/lib/lab/messages/<locale>.ts: one table of every lab_* message per locale.
// The Lab resolves dotted registry keys at runtime (t('lab.f.twr.title')); looking
// them up on the whole paraglide module made the bundler keep all ~11k messages
// (a 2.5 MB chunk on /lab), and one table holding all 14 translations of each
// message was still 637 KB br. One module per locale lets t() load only the
// reader's (src/lib/lab/t.ts). `{name}` placeholders are kept verbatim; t() fills
// them. A key a locale lacks takes its en-US text, as paraglide's own fallback does.
// Run after adding or removing lab_* keys; src/lib/lab/i18n-parity.test.ts fails
// until the tables match messages/*.json.
import fs from 'node:fs';

const OUT_DIR = 'src/lib/lab/messages';
const en = JSON.parse(fs.readFileSync('messages/en-US.json', 'utf8'));
const keys = Object.keys(en)
  .filter((k) => k.startsWith('lab_'))
  .sort();

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });

const locales = fs
  .readdirSync('messages')
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -'.json'.length))
  .sort();

for (const locale of locales) {
  const bundle = JSON.parse(fs.readFileSync(`messages/${locale}.json`, 'utf8'));
  const body = keys
    .map((k) => `  ${k}: ${JSON.stringify(typeof bundle[k] === 'string' ? bundle[k] : en[k])},`)
    .join('\n');
  fs.writeFileSync(
    `${OUT_DIR}/${locale}.ts`,
    `// Generated by scripts/i18n-tools/gen-lab-messages.mjs from messages/${locale}.json. Do not edit.
const messages: Record<string, string> = {
${body}
};

export default messages;
`,
  );
}
console.log(`${OUT_DIR}: ${keys.length} lab messages x ${locales.length} locales`);
