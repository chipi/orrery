// Writes src/lib/lab/lab-messages.ts: an explicit table of every lab_* message.
// The Lab resolves dotted registry keys at runtime (t('lab.f.twr.title')); looking
// them up on the whole paraglide module made the bundler keep all ~11k messages
// (a 2.5 MB chunk on /lab). The table keeps only the lab ones.
// Run after adding or removing lab_* keys; src/lib/lab/i18n-parity.test.ts fails
// until the table matches messages/en-US.json.
import fs from 'node:fs';

const OUT = 'src/lib/lab/lab-messages.ts';
const en = JSON.parse(fs.readFileSync('messages/en-US.json', 'utf8'));
const keys = Object.keys(en)
  .filter((k) => k.startsWith('lab_'))
  .sort();

const body = keys.map((k) => `  ${k}: m.${k},`).join('\n');
fs.writeFileSync(
  OUT,
  `// Generated by scripts/i18n-tools/gen-lab-messages.mjs from messages/en-US.json. Do not edit.
import * as m from '$lib/paraglide/messages';

export const LAB_MESSAGES = {
${body}
};
`,
);
console.log(`${OUT}: ${keys.length} lab messages`);
