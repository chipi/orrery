// Default stems from a binding form: Latin / Cyrillic words lose their last two letters and take
// \p{L}* (inflection), CJK stays, ko spaces become optional, hi separators optional, ar words may
// carry the article.
const stemOf = (loc, form) => {
  if (loc === 'ja' || loc === 'zh-CN') return form;
  if (loc === 'ko') return form.replace(/ /g, ' ?');
  if (loc === 'hi') return form.replace(/[ -]/g, '[ -]?');
  if (loc === 'ar') return form.split(' ').join(' (?:ال)?');
  return form
    .split(' ')
    .map((w) => (w.length >= 5 ? `${w.slice(0, -2)}\\p{L}*` : w))
    .join(' ');
};

